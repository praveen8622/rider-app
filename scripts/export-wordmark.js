// Writes the logo's Y (arms + road, no rider or pin) as path data for the in-app wordmark:
//   node scripts/export-wordmark.js
// Output: src/components/wordmark-glyph.ts. Re-run after changing the mark in yroad.js.
const fs = require('node:fs');
const path = require('node:path');
const { ROAD, ARMS, BOTTOM } = require('./yroad');

// Bounding box of everything drawn (the road is cut flat at BOTTOM).
const nums = (d) => d.match(/-?\d+(\.\d+)?/g).map(Number);
const pts = [ARMS.main, ARMS.inner, ROAD.outer].flatMap((d) => {
  const n = nums(d);
  const out = [];
  for (let i = 0; i + 1 < n.length; i += 2) out.push([n[i], Math.min(n[i + 1], BOTTOM)]);
  return out;
});
const minX = Math.floor(Math.min(...pts.map((p) => p[0])));
const maxX = Math.ceil(Math.max(...pts.map((p) => p[0])));
const minY = Math.floor(Math.min(...pts.map((p) => p[1])));
const maxY = BOTTOM;

// The road outlines are sampled finely for the 1024px icon; at letter size every 8th point
// looks the same and keeps the file small. Ends of each side are always kept.
function thin(d, every = 8) {
  const parts = d.replace(/^M/, '').replace(/ Z$/, '').split(' L');
  const half = parts.length / 2;
  const keep = parts.filter((_, i) => i % every === 0 || i === half - 1 || i === half || i === parts.length - 1);
  return `M${keep.join(' L')} Z`;
}
ROAD.outer = thin(ROAD.outer);
ROAD.edge = thin(ROAD.edge);
ROAD.asphalt = thin(ROAD.asphalt);

const file = `// Generated by scripts/export-wordmark.js from scripts/yroad.js. Do not edit by hand.
/** The logo's Y on its own: two arm bands and the road in perspective. */
export const Y_GLYPH = {
  viewBox: '${minX} ${minY} ${maxX - minX} ${maxY - minY}',
  /** Width / height. */
  aspect: ${((maxX - minX) / (maxY - minY)).toFixed(4)},
  /** The road is cut flat here (same units as the paths). */
  bottom: ${BOTTOM},
  arm: '${ARMS.main}',
  armInner: '${ARMS.inner}',
  roadOuter: '${ROAD.outer}',
  roadEdge: '${ROAD.edge}',
  roadAsphalt: '${ROAD.asphalt}',
  roadLane: '${ROAD.lane}',
} as const;
`;
const out = path.join(__dirname, '..', 'src', 'components', 'wordmark-glyph.ts');
fs.writeFileSync(out, file);
console.log(`wrote ${path.relative(process.cwd(), out)}  viewBox ${minX} ${minY} ${maxX - minX} ${maxY - minY}  (${(file.length / 1024).toFixed(1)} KB)`);
